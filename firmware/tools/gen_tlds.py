#!/usr/bin/env python3
"""Regenerates lib/core/Tlds.h from IANA's list of top-level domains (downloaded to a temp folder). Run before a release: python3 tools/gen_tlds.py"""
import pathlib, re, sys, tempfile, urllib.request

URL = "https://data.iana.org/TLD/tlds-alpha-by-domain.txt"
out = pathlib.Path(__file__).resolve().parent.parent / "lib/core/Tlds.h"
with tempfile.TemporaryDirectory() as tmp:
    path = pathlib.Path(tmp) / "tlds.txt"
    path.write_bytes(urllib.request.urlopen(urllib.request.Request(URL, headers={"User-Agent": "ultimatrix-gen-tlds"}), timeout=60).read())
    lines = path.read_text().splitlines()
version = lines[0].lstrip("# ").strip()
tlds = sorted({l.strip().lower() for l in lines[1:] if re.fullmatch(r"[A-Za-z0-9-]+", l.strip())})
if len(tlds) < 1000:
    sys.exit("the list looks too short; nothing written")
body = "\n".join('  "' + ("|" if i == 0 else "") + "|".join(tlds[i:i + 12]) + '|"' for i in range(0, len(tlds), 12))
out.write_text(f"""// Generated by tools/gen_tlds.py from IANA's list ({version}); {len(tlds)} top-level domains. Do not edit.
// A web page that rebinds its DNS name to this clock needs a real domain, so a host name under one of these is refused (see main.cpp HostGuard).
#pragma once
static const char kTlds[] =
{body};
""")
print(len(tlds), "TLDs written to", out)
