#!/usr/bin/env python3
"""Generate clockfaces/home/SourceArt.h: the Impact letters (four heights) and the small icons the Now playing page shows
when a player has nothing but a source to show ("TV", "Line-in"...). Needs Pillow and macOS's Impact font; the header is committed."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

OUT = Path(__file__).resolve().parent.parent / "clockfaces/home/SourceArt.h"
IMPACT = "/System/Library/Fonts/Supplemental/Impact.ttf"
CHARS = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-."
HEIGHTS = (32, 22, 15, 11)


def glyph_rows(ch, size, height):
    font = ImageFont.truetype(IMPACT, size)
    im = Image.new("L", (80, 90), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((10, 10 + height), ch, font=font, fill=255, anchor="ls")
    crop = im.crop((0, 10, 80, 10 + height))
    cols = [x for x in range(80) if any(crop.getpixel((x, y)) > 127 for y in range(height))]
    if not cols:
        return max(2, height // 4), [0] * height
    x0, x1 = cols[0], cols[-1]
    w = x1 - x0 + 1
    rows = []
    for y in range(height):
        v = 0
        for x in range(x0, x1 + 1):
            v = v << 1 | (crop.getpixel((x, y)) > 127)
        rows.append(v)
    return w, rows


def cap_size(height):
    for size in range(8, 90):
        l, t, r, b = ImageFont.truetype(IMPACT, size).getbbox("H", anchor="ls")
        if -t >= height:
            return size
    raise SystemExit("no size")


def rgb565(c):
    return (c[0] >> 3) << 11 | (c[1] >> 2) << 5 | c[2] >> 3


GREY, DK, BL, RED, WH, AM, BODY, SCR = (150, 160, 175), (60, 68, 84), (70, 140, 255), (255, 50, 50), (235, 240, 255), (255, 180, 40), (120, 150, 190), (40, 100, 175)


def canvas():
    im = Image.new("RGB", (64, 64), (0, 0, 0))
    return im, ImageDraw.Draw(im)


def icons():
    out = []
    im, d = canvas()  # tv
    d.line([(24, 8), (31, 15)], fill=BODY); d.line([(39, 8), (32, 15)], fill=BODY)
    d.rectangle((9, 16, 54, 44), fill=BODY); d.rectangle((12, 19, 51, 41), fill=SCR)
    d.rectangle((15, 45, 20, 46), fill=BODY); d.rectangle((43, 45, 48, 46), fill=BODY)
    out.append(("tv", im))
    im, d = canvas()  # line-in
    d.line([(6, 46), (10, 46), (14, 40), (16, 34)], fill=GREY, width=2)
    d.rectangle((16, 29, 30, 38), fill=GREY); d.rectangle((32, 30, 33, 37), fill=DK); d.rectangle((35, 30, 36, 37), fill=GREY)
    d.rectangle((38, 30, 39, 37), fill=DK); d.rectangle((41, 31, 50, 36), fill=WH); d.rectangle((51, 32, 52, 35), fill=WH)
    out.append(("line", im))
    im, d = canvas()  # optical
    d.rectangle((18, 20, 45, 43), fill=GREY); d.rectangle((22, 24, 41, 39), fill=DK); d.ellipse((28, 29, 35, 36), fill=RED)
    for a in ((32, 13, 32, 18), (14, 32, 10, 32), (50, 32, 54, 32), (20, 17, 17, 14), (44, 17, 47, 14)):
        d.line(a, fill=RED)
    out.append(("optical", im))
    im, d = canvas()  # hdmi
    d.polygon([(12, 22), (52, 22), (52, 34), (47, 41), (17, 41), (12, 34)], fill=GREY)
    d.polygon([(16, 26), (48, 26), (48, 33), (44, 37), (20, 37), (16, 33)], fill=DK)
    for x in range(20, 45, 3):
        d.rectangle((x, 29, x + 1, 33), fill=AM)
    out.append(("hdmi", im))
    im, d = canvas()  # bluetooth
    d.line([(23, 26), (41, 38), (32, 47), (32, 15), (41, 26), (23, 38)], fill=BL, width=3)
    out.append(("bluetooth", im))
    im, d = canvas()  # airplay
    d.line([(24, 38), (14, 38), (14, 16), (50, 16), (50, 38), (40, 38)], fill=GREY, width=2)
    d.polygon([(32, 28), (44, 44), (20, 44)], fill=WH)
    out.append(("airplay", im))
    im, d = canvas()  # radio
    d.line([(44, 28), (50, 14)], fill=GREY)
    d.rectangle((12, 28, 52, 47), fill=GREY); d.rectangle((14, 30, 50, 45), fill=DK); d.ellipse((17, 32, 30, 44), outline=AM)
    for y in range(34, 43, 3):
        for x in range(20, 28, 3):
            d.point((x, y), fill=AM)
    d.rectangle((35, 33, 47, 34), fill=GREY); d.rectangle((35, 39, 47, 40), fill=GREY); d.rectangle((41, 31, 42, 42), fill=WH)
    out.append(("radio", im))
    im, d = canvas()  # phono
    d.ellipse((12, 17, 44, 49), fill=(30, 34, 46), outline=GREY); d.ellipse((20, 25, 36, 41), outline=DK); d.ellipse((24, 29, 32, 37), fill=AM)
    d.line([(52, 18), (50, 34), (40, 40)], fill=WH, width=2)
    out.append(("phono", im))
    return out


def main():
    lines = ["// Generated by tools/gen_source_art.py: do not edit.", "#pragma once", "#include <stdint.h>", "",
             "namespace home {", "namespace sourceart {", "", f'constexpr const char *kChars = "{CHARS}";', f"constexpr int kCharCount = {len(CHARS)};", ""]
    for h in HEIGHTS:
        size = cap_size(h)
        widths, flat = [], []
        for ch in CHARS:
            w, rows = glyph_rows(ch, size, h)
            widths.append(w); flat += rows
        lines.append(f"constexpr uint8_t kW{h}[] = {{{','.join(map(str, widths))}}};")
        lines.append(f"constexpr uint32_t kRows{h}[] = {{{','.join(hex(v) for v in flat)}}};")
    lines += ["struct Font { uint8_t height; const uint8_t *width; const uint32_t *rows; };",
              "constexpr Font kFonts[] = {" + ",".join(f"{{{h}, kW{h}, kRows{h}}}" for h in HEIGHTS) + "};", "",
              "struct Icon { uint8_t w, h; const uint16_t *palette; const uint8_t *pixels; };  // pixels: palette index, 0 is clear"]
    names = []
    for name, im in icons():
        box = im.getbbox()
        im = im.crop(box)
        colours = sorted({c for c in im.getdata() if c != (0, 0, 0)})
        assert len(colours) < 16, (name, len(colours))
        pal = [0] + [rgb565(c) for c in colours]
        px = [0 if c == (0, 0, 0) else colours.index(c) + 1 for c in im.getdata()]
        lines.append(f"constexpr uint16_t kPal_{name}[] = {{{','.join(hex(v) for v in pal)}}};")
        lines.append(f"constexpr uint8_t kPx_{name}[] = {{{','.join(map(str, px))}}};")
        names.append((name, im.width, im.height))
    lines.append("constexpr Icon kIcons[] = {" + ",".join(f"{{{w},{h},kPal_{n},kPx_{n}}}" for n, w, h in names) + "};")
    lines.append("enum IconId : uint8_t { " + ", ".join(f"ICON_{n.upper()}" for n, _, _ in names) + ", ICON_NONE };")
    lines += ["", "}  // namespace sourceart", "}  // namespace home", ""]
    OUT.write_text("\n".join(lines))
    print(OUT, OUT.stat().st_size, [(n, w, h) for n, w, h in names])


main()
