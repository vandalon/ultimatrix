#!/usr/bin/env python3
# Writes TzDb.h: timezone names (as the settings page offers them) and their POSIX rules.
# Source: tools/zones.csv, from https://github.com/nayarsystems/posix_tz_db. CMake runs this on every build:
#   python3 tools/gen_tzdb.py <output TzDb.h> [zones.csv]
# To refresh zones.csv from upstream: python3 tools/gen_tzdb.py --update
import csv, io, os, sys, urllib.request

URL = "https://raw.githubusercontent.com/nayarsystems/posix_tz_db/master/zones.csv"
# Names the browser may list that the source does not have (renamed zones): alias -> name in the source
ALIASES = {
    "UTC": "Etc/UTC", "GMT": "Etc/GMT", "Europe/Kyiv": "Europe/Kiev", "Asia/Calcutta": "Asia/Kolkata",
    "Asia/Rangoon": "Asia/Yangon", "Atlantic/Faeroe": "Atlantic/Faroe", "Pacific/Kanton": "Pacific/Enderbury",
    "America/Ciudad_Juarez": "America/Ojinaga",
}

here = os.path.dirname(os.path.abspath(__file__))
default_csv = os.path.join(here, "zones.csv")

if sys.argv[1:] == ["--update"]:
    raw = urllib.request.urlopen(URL).read().decode("utf-8")
    zones = {name: rule for name, rule in csv.reader(io.StringIO(raw))}
    for alias, name in ALIASES.items():
        if alias not in zones and name in zones:
            zones[alias] = zones[name]
    with open(default_csv, "w", encoding="utf-8", newline="") as f:
        csv.writer(f, lineterminator="\n").writerows((n, zones[n]) for n in sorted(zones))
    print("%d zones -> %s" % (len(zones), default_csv))
    sys.exit(0)

out = sys.argv[1]
src = sys.argv[2] if len(sys.argv) > 2 else default_csv
with open(src, encoding="utf-8") as f:
    zones = {name: rule for name, rule in csv.reader(f)}

lines = [
    "// Generated by tools/gen_tzdb.py from tools/zones.csv: do not edit.",
    "// Timezone name -> POSIX rule, sorted by name (byte order) for the binary search in TimeService.cpp.",
    "#pragma once",
    "",
    "struct UmTzEntry { const char *name; const char *posix; };",
    "",
    "static const UmTzEntry UM_TZ_DB[] = {",
]
for name in sorted(zones, key=lambda n: n.encode()):
    lines.append('  {"%s", "%s"},' % (name, zones[name].replace("\\", "\\\\").replace('"', '\\"')))
lines += ["};", "", "static const unsigned UM_TZ_DB_SIZE = sizeof(UM_TZ_DB) / sizeof(UM_TZ_DB[0]);", ""]
os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
