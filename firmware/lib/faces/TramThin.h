// TramThin: TramDot letters and digits with 1 px strokes, upper and lower case. 8 rows: capitals use rows 0..6, the lower-case body rows 2..6,
// ascenders reach row 0 or 1, descenders row 7. Header only.
#pragma once

#include <stdint.h>

namespace facekit {

struct ThinGlyph { uint8_t w; uint8_t rows[8]; };  // row 0 = top; left dot = bit (w - 1)

// The glyph of a letter or digit, or nullptr
inline const ThinGlyph *thinGlyph(char c) {
  static const ThinGlyph UPPER[26] = {
    {4, {0x06, 0x09, 0x09, 0x0F, 0x09, 0x09, 0x09, 0x00}},  // A
    {4, {0x0E, 0x09, 0x09, 0x0E, 0x09, 0x09, 0x0E, 0x00}},  // B
    {4, {0x07, 0x08, 0x08, 0x08, 0x08, 0x08, 0x07, 0x00}},  // C
    {4, {0x0E, 0x09, 0x09, 0x09, 0x09, 0x09, 0x0E, 0x00}},  // D
    {4, {0x0F, 0x08, 0x08, 0x0E, 0x08, 0x08, 0x0F, 0x00}},  // E
    {4, {0x0F, 0x08, 0x08, 0x0E, 0x08, 0x08, 0x08, 0x00}},  // F
    {4, {0x07, 0x08, 0x08, 0x0B, 0x09, 0x09, 0x07, 0x00}},  // G
    {4, {0x09, 0x09, 0x09, 0x0F, 0x09, 0x09, 0x09, 0x00}},  // H
    {3, {0x07, 0x02, 0x02, 0x02, 0x02, 0x02, 0x07, 0x00}},  // I
    {4, {0x03, 0x01, 0x01, 0x01, 0x01, 0x09, 0x06, 0x00}},  // J
    {4, {0x09, 0x0A, 0x0C, 0x0C, 0x0A, 0x09, 0x09, 0x00}},  // K
    {4, {0x08, 0x08, 0x08, 0x08, 0x08, 0x08, 0x0F, 0x00}},  // L
    {5, {0x11, 0x1B, 0x15, 0x11, 0x11, 0x11, 0x11, 0x00}},  // M
    {5, {0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11, 0x00}},  // N
    {4, {0x06, 0x09, 0x09, 0x09, 0x09, 0x09, 0x06, 0x00}},  // O
    {4, {0x0E, 0x09, 0x09, 0x0E, 0x08, 0x08, 0x08, 0x00}},  // P
    {4, {0x06, 0x09, 0x09, 0x09, 0x09, 0x0A, 0x05, 0x00}},  // Q
    {4, {0x0E, 0x09, 0x09, 0x0E, 0x0C, 0x0A, 0x09, 0x00}},  // R
    {4, {0x07, 0x08, 0x08, 0x06, 0x01, 0x01, 0x0E, 0x00}},  // S
    {5, {0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04, 0x00}},  // T
    {4, {0x09, 0x09, 0x09, 0x09, 0x09, 0x09, 0x06, 0x00}},  // U
    {5, {0x11, 0x11, 0x11, 0x11, 0x0A, 0x0A, 0x04, 0x00}},  // V
    {5, {0x11, 0x11, 0x11, 0x15, 0x15, 0x1B, 0x11, 0x00}},  // W
    {5, {0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11, 0x00}},  // X
    {5, {0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04, 0x00}},  // Y
    {4, {0x0F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x0F, 0x00}},  // Z
  };
  static const ThinGlyph LOWER[26] = {
    {4, {0x00, 0x00, 0x06, 0x01, 0x07, 0x09, 0x07, 0x00}},  // a
    {4, {0x08, 0x08, 0x08, 0x0E, 0x09, 0x09, 0x0E, 0x00}},  // b
    {3, {0x00, 0x00, 0x03, 0x04, 0x04, 0x04, 0x03, 0x00}},  // c
    {4, {0x01, 0x01, 0x01, 0x07, 0x09, 0x09, 0x07, 0x00}},  // d
    {4, {0x00, 0x00, 0x06, 0x09, 0x0F, 0x08, 0x07, 0x00}},  // e
    {3, {0x03, 0x04, 0x07, 0x04, 0x04, 0x04, 0x04, 0x00}},  // f
    {4, {0x00, 0x00, 0x07, 0x09, 0x09, 0x07, 0x01, 0x06}},  // g
    {4, {0x08, 0x08, 0x08, 0x0E, 0x09, 0x09, 0x09, 0x00}},  // h
    {1, {0x00, 0x01, 0x00, 0x01, 0x01, 0x01, 0x01, 0x00}},  // i
    {2, {0x00, 0x01, 0x00, 0x01, 0x01, 0x01, 0x01, 0x02}},  // j
    {4, {0x08, 0x08, 0x09, 0x0A, 0x0C, 0x0A, 0x09, 0x00}},  // k
    {2, {0x02, 0x02, 0x02, 0x02, 0x02, 0x02, 0x01, 0x00}},  // l
    {5, {0x00, 0x00, 0x1A, 0x15, 0x15, 0x15, 0x15, 0x00}},  // m
    {4, {0x00, 0x00, 0x0E, 0x09, 0x09, 0x09, 0x09, 0x00}},  // n
    {4, {0x00, 0x00, 0x06, 0x09, 0x09, 0x09, 0x06, 0x00}},  // o
    {4, {0x00, 0x00, 0x0E, 0x09, 0x09, 0x0E, 0x08, 0x08}},  // p
    {4, {0x00, 0x00, 0x07, 0x09, 0x09, 0x07, 0x01, 0x01}},  // q
    {4, {0x00, 0x00, 0x0B, 0x0C, 0x08, 0x08, 0x08, 0x00}},  // r
    {4, {0x00, 0x00, 0x07, 0x08, 0x06, 0x01, 0x0E, 0x00}},  // s
    {3, {0x00, 0x04, 0x07, 0x04, 0x04, 0x04, 0x03, 0x00}},  // t
    {4, {0x00, 0x00, 0x09, 0x09, 0x09, 0x09, 0x07, 0x00}},  // u
    {5, {0x00, 0x00, 0x11, 0x11, 0x11, 0x0A, 0x04, 0x00}},  // v
    {5, {0x00, 0x00, 0x11, 0x11, 0x15, 0x15, 0x0A, 0x00}},  // w
    {3, {0x00, 0x00, 0x05, 0x05, 0x02, 0x05, 0x05, 0x00}},  // x
    {4, {0x00, 0x00, 0x09, 0x09, 0x09, 0x07, 0x01, 0x06}},  // y
    {4, {0x00, 0x00, 0x0F, 0x02, 0x04, 0x08, 0x0F, 0x00}},  // z
  };
  static const ThinGlyph DIGIT[10] = {
    {4, {0x06, 0x09, 0x09, 0x09, 0x09, 0x09, 0x06, 0x00}},  // 0
    {3, {0x02, 0x06, 0x02, 0x02, 0x02, 0x02, 0x07, 0x00}},  // 1
    {4, {0x06, 0x09, 0x01, 0x02, 0x04, 0x08, 0x0F, 0x00}},  // 2
    {4, {0x0E, 0x01, 0x01, 0x06, 0x01, 0x01, 0x0E, 0x00}},  // 3
    {5, {0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02, 0x00}},  // 4
    {4, {0x0F, 0x08, 0x0E, 0x01, 0x01, 0x09, 0x06, 0x00}},  // 5
    {4, {0x06, 0x08, 0x08, 0x0E, 0x09, 0x09, 0x06, 0x00}},  // 6
    {4, {0x0F, 0x01, 0x01, 0x02, 0x02, 0x04, 0x04, 0x00}},  // 7
    {4, {0x06, 0x09, 0x09, 0x06, 0x09, 0x09, 0x06, 0x00}},  // 8
    {4, {0x06, 0x09, 0x09, 0x07, 0x01, 0x01, 0x06, 0x00}},  // 9
  };
  if (c >= '0' && c <= '9') return &DIGIT[c - '0'];
  if (c >= 'A' && c <= 'Z') return &UPPER[c - 'A'];
  if (c >= 'a' && c <= 'z') return &LOWER[c - 'a'];
  return nullptr;
}

}  // namespace facekit
